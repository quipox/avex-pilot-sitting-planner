// Builds embed/atpl-planner-embed.html from index.html.
// Takes the blocks marked data-embed (questions, plan editor, disclaimer) and the planner script,
// and wraps them in a Shadow DOM so the blog template and the planner cannot affect each other.
// Run after any change to the planner: npm run build:embed
const fs = require("fs");
const path = require("path");
const SRC = path.join(__dirname, "..", "index.html");
const OUT = path.join(__dirname, "..", "embed", "atpl-planner-embed.html");

const src = fs.readFileSync(SRC, "utf8");
let css = src.match(/<style>([\s\S]*?)<\/style>/)[1];
let js = src.match(/<script>([\s\S]*?)<\/script>/)[1];

// ---- markup: every element carrying data-embed, in page order
const blocks = [...src.matchAll(/<(section|aside)([^>]*\bdata-embed\b[^>]*)>([\s\S]*?)<\/\1>/g)]
  .map(m => `<${m[1]}${m[2].replace(/\s*\bid="[^"]*"/, "")}>${m[3]}</${m[1]}>`);
if (blocks.length < 3) throw new Error("expected 3 data-embed blocks, found " + blocks.length);
let html = `<div class="wrap">
<header>
  <p class="eyebrow">Interactive planner</p>
  <h3 class="h2">Build your own ATPL study plan</h3>
  <p class="sub">Answer a few questions to get a sitting plan with dates, hours a day and the 18-month clock, then move the subjects to make it your own.</p>
</header>
${blocks.join("\n")}
</div>`;
// one heading level down so the block sits inside an article section
html = html.replace(/<h3/g, "<h4").replace(/<\/h3>/g, "</h4>").replace(/<h2/g, "<h3 class=\"h2\"").replace(/<\/h2>/g, "</h3>");
html = html.replace(/<h4 class="h2">/, '<h3 class="h2">').replace(/<\/h4>\n  <p class="sub">Answer/, '</h3>\n  <p class="sub">Answer');
js = js.replace(/<h3>/g, "<h4>").replace(/<\/h3>/g, "</h4>");
css = css.replace(/\.sit h3/g, ".sit h4").replace(/\.checks h3/g, ".checks h4").replace(/\.disclaimer h2/g, ".disclaimer .h2");

// ---- CSS for a shadow root
css = css.replace(/:root\{/g, ":host{").replace(/--sans:[^;]+;/, "--sans:inherit;");
css = `:host{display:block;background:#fff;color:var(--fg);font-family:inherit;line-height:1.5;max-width:1080px;margin:32px auto;text-align:left}
p{margin-top:0}
button,input{font-family:inherit}
.wrap{display:grid;gap:28px;padding:0}
.h2{font-size:clamp(20px,2.4vw,26px);font-weight:800;margin:0 0 6px;color:var(--navy)}
` + css;

// ---- JS: planner logic only, element lookups inside the shadow root
js = js.slice(0, js.indexOf("/* decision flow SVG */"));
js = js.replace(/\/\* @host \*\/[\s\S]*?\/\* @end-host \*\//, "");
js = js.replace('document.addEventListener("keydown"', 'ROOT.addEventListener("keydown"');

const out = `<!--
  AVIATIONEXAM · ATPL STUDY PLANNER (embeddable block) — generated by scripts/build-embed.js, do not edit by hand.
  Paste this whole block, unchanged, where [INTERACTIVE PLANNER] appears in the article.
  - Self-contained: no external files, fonts or libraries. It uses the page's own font.
  - Isolated with Shadow DOM: the blog's CSS cannot change it and its CSS cannot change the blog.
  - Saves the student's plan in their own browser (localStorage); nothing is sent anywhere.
  - Needs the CMS to keep the inline <script>. If the editor strips scripts, leave the block out:
    the article text already includes the four plans as static content.
-->
<div id="avex-atpl-planner"><noscript>The interactive planner needs JavaScript. The four study plans are listed in the article.</noscript></div>
<script>
(function(){
var HOST = document.getElementById("avex-atpl-planner");
if (!HOST || HOST.shadowRoot) return;
var ROOT = HOST.attachShadow({mode: "open"});
ROOT.innerHTML = "<style>" + ${JSON.stringify(css)} + "</style>" + ${JSON.stringify(html)};
function $(id){ return ROOT.getElementById(id); }
${js}
})();
</script>
`;
fs.writeFileSync(OUT, out);
console.log("written", path.relative(process.cwd(), OUT), out.length, "bytes");
